/** The receipt: what was revoked, each transaction, and the window QoreX used. */
import { useState } from "react";
import { shortAddress } from "../lib/format";
import { TxLink } from "./TxLink";
import type { ReceiptEntry } from "./useRevoke";

/** Shorten long addresses for the on-screen list; the copied receipt keeps them in full. */
const shorten = (text: string) => text.replace(/\b(qor1[0-9a-z]{30,}|0x[0-9a-fA-F]{40})\b/g, shortAddress);


export function receiptMarkdown(account: string, entries: ReceiptEntry[]): string {
  const lines = [
    `# Unyoke receipt`,
    ``,
    `Account: ${account} · QoreChain testnet (qorechain-diana)`,
    ``,
    `| # | Lane | What | Transaction | Window used |`,
    `| --- | --- | --- | --- | --- |`,
    ...entries.map(
      (e, i) =>
        `| ${i + 1} | ${e.lane} | ${e.what} | ${e.txHash} | ${
          e.evidence?.found ? `${e.evidence.allowedTargets.join(", ") || "any contract"} · ${e.evidence.maxTxs} tx · used ${e.evidence.usedTxs}` : e.lane === "Native" ? "none needed (native message)" : "not read"
        } |`,
    ),
    ``,
    `Each revoke was checked on chain afterwards. Generated by Unyoke.`,
  ];
  return lines.join("\n");
}

export function Receipt({ account, entries }: { account: string; entries: ReceiptEntry[] }) {
  const [copied, setCopied] = useState(false);
  if (entries.length === 0) return null;
  return (
    <section className="receipt" aria-label="Receipt">
      <div className="receipt-head">
        <div>
          <span className="kicker mono">receipt</span>
          <h3>
            {entries.length} permission{entries.length === 1 ? "" : "s"} removed
          </h3>
        </div>
        <button
          type="button"
          className="ghost"
          onClick={async () => {
            await navigator.clipboard.writeText(receiptMarkdown(account, entries));
            setCopied(true);
            setTimeout(() => setCopied(false), 1800);
          }}
        >
          {copied ? "Copied ✓" : "Copy receipt"}
        </button>
      </div>
      <ol>
        {entries.map((e) => (
          <li key={e.key + e.txHash}>
            <span className={`lane-tag ${e.lane === "EVM" ? "evm" : "native"}`}>{e.lane}</span>
            <span className="receipt-what" title={e.what}>{shorten(e.what)}</span>
            <TxLink className="mono" hash={e.txHash}>
              {e.txHash.slice(0, 12)}…
            </TxLink>
            {e.evidence?.found && (
              <span className={`receipt-window ${e.evidence.tight ? "tight" : ""}`}>
                {e.evidence.tight ? "1-tx window, this token only ✓" : `window: ${e.evidence.maxTxs} tx`}
              </span>
            )}
          </li>
        ))}
      </ol>
    </section>
  );
}
