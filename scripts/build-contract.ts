/**
 * Compile contracts/PqcKeyCheck.sol with solc and write its ABI and bytecode to
 * src/lib/pqcKeyCheckArtifact.ts, so the app and the deploy script use exactly
 * what was compiled. Run: pnpm build:contract
 */
import { readFileSync, writeFileSync } from "node:fs";
// @ts-expect-error solc ships no types
import solc from "solc";

const source = readFileSync("contracts/PqcKeyCheck.sol", "utf8");
const input = {
  language: "Solidity",
  sources: { "PqcKeyCheck.sol": { content: source } },
  settings: { optimizer: { enabled: true, runs: 200 }, evmVersion: "cancun", outputSelection: { "*": { "*": ["abi", "evm.bytecode.object"] } } },
};
const out = JSON.parse(solc.compile(JSON.stringify(input)));
const errors = (out.errors ?? []).filter((e: { severity: string }) => e.severity === "error");
if (errors.length) {
  for (const e of errors) console.error(e.formattedMessage);
  process.exit(1);
}
const c = out.contracts["PqcKeyCheck.sol"].PqcKeyCheck;
writeFileSync(
  "src/lib/pqcKeyCheckArtifact.ts",
  `// Generated by scripts/build-contract.ts from contracts/PqcKeyCheck.sol (solc ${solc.version()}). Do not edit.\n` +
    `export const PQC_KEY_CHECK_ABI = ${JSON.stringify(c.abi, null, 2)} as const;\n\n` +
    `export const PQC_KEY_CHECK_BYTECODE = "0x${c.evm.bytecode.object}" as const;\n`,
);
console.log(`compiled PqcKeyCheck with solc ${solc.version()}: ${c.evm.bytecode.object.length / 2} bytes`);
